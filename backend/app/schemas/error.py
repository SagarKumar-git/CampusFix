"""Standardized error models including API Error Envelopes and RFC 7807 Problem Details."""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class ValidationErrorItem(BaseModel):
    """Granular error descriptor for individual field validation failures."""

    field: str | None = Field(default=None, description="Name or path of the offending field")
    message: str = Field(description="Human-readable description of the constraint failure")
    type: str | None = Field(default=None, description="Pydantic or schema error type identifier")

    model_config = ConfigDict(extra="forbid")


class ErrorDetail(BaseModel):
    """Structured error payload providing machine and human diagnostic context."""

    code: str = Field(
        description="Machine-readable error code (e.g. RESOURCE_NOT_FOUND, VALIDATION_ERROR)"
    )
    message: str = Field(description="Human-readable summary of the error condition")
    details: Any | None = Field(
        default=None,
        description="Optional supplementary diagnostic data or list of field validation errors",
    )

    model_config = ConfigDict(extra="forbid")


class ErrorEnvelope(BaseModel):
    """Standardized top-level API error envelope returned on client and server errors."""

    success: Literal[False] = False
    error: ErrorDetail
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="UTC timestamp when the error was generated",
    )

    model_config = ConfigDict(extra="forbid")


class ProblemDetails(BaseModel):
    """RFC 7807 Problem Details representation for HTTP APIs."""

    type: str = Field(
        default="about:blank",
        description="URI reference that identifies the problem type",
    )
    title: str = Field(
        description="Short, human-readable summary of the problem type",
    )
    status: int = Field(
        description="HTTP status code generated by the origin server for this occurrence",
    )
    detail: str | None = Field(
        default=None,
        description="Human-readable explanation specific to this occurrence of the problem",
    )
    instance: str | None = Field(
        default=None,
        description="URI reference that identifies the specific occurrence of the problem",
    )
    code: str | None = Field(
        default=None,
        description="Machine-readable error code aligned with CampusFix domain error taxonomy",
    )
    invalid_params: list[ValidationErrorItem] | None = Field(
        default=None,
        description="List of invalid request parameters and reasons when status is 422",
    )
    timestamp: datetime | None = Field(
        default_factory=lambda: datetime.now(UTC),
        description="UTC timestamp identifying when the problem occurred",
    )

    model_config = ConfigDict(extra="allow")
